"""GTM-190 (signed by Albert, 20-11 06:46): three question pages with the Claude Code templates, EN and ES, and their
index (/templates/, /es/plantillas/). CA comes when the program's catalog has Catalan.

Every text but the titles, the steps in ES and the closing paragraph in ES comes from the export of BV-266 in
qtorb/rosmarops-templates (templates/claude-code/<use>/: the settings file and a README.md whose last line is
«Generated by RosmarOps <version>. Do not edit by hand.»), copied here into observatory/data/templates/. Until that
copy exists nothing is built: no page, no sitemap entry, no llms.txt line and no footer link, so nothing goes out half
made. Same shell and styles as the sandbox guide; no new CSS or JavaScript, no structured data.
"""

import html
import re
from pathlib import Path

import sandbox_section

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
EXPORT = ROOT / "observatory" / "data" / "templates" / "claude-code"
REPO = "https://github.com/qtorb/rosmarops-templates"
LANGS = ("en", "es")
INDEX = {"en": "/templates/", "es": "/es/plantillas/"}
FOOTER_LABEL = {"en": "Templates", "es": "Plantillas", "ca": "Plantilles"}  # the footer link points to the EN page

# The three pages: template, path and title (literal, GTM-190). FOLDER is the use folder of the BV-266 export; it is
# filled in when the export lands (the brief does not name it), and a page is built only when its folder exists.
PAGES = {
    "P0": {"en": ("/templates/claude-code-read-only/", "How to make Claude Code read your project without changing anything"),
           "es": ("/es/plantillas/claude-code-solo-lectura/", "Cómo hacer que Claude Code lea tu proyecto sin cambiar nada")},
    "P1": {"en": ("/templates/claude-code-no-web/", "How to stop Claude Code from fetching web pages or running curl and wget"),
           "es": ("/es/plantillas/claude-code-sin-web/", "Cómo impedir que Claude Code abra páginas web o use curl y wget")},
    "P2": {"en": ("/templates/claude-code-sandbox/", "How to run Claude Code in its sandbox with network only to npm and GitHub"),
           "es": ("/es/plantillas/claude-code-sandbox/", "Cómo usar Claude Code en su sandbox con red solo a npm y GitHub")},
}
FOLDER = {"P0": None, "P1": None, "P2": None}
DEST = ".claude/settings.json"

# Literal texts of GTM-190 §4 and §6 (ES), and the labels of §5.
STEPS = {"es": ["Abre la carpeta de tu agente en <code>templates/</code>.",
                "Elige el uso que encaja con cómo trabajas. Cada uno dice qué puede hacer el agente sin preguntar y qué pregunta antes.",
                "Copia el fichero en tu proyecto, o pide a la skill de RosmarOps que lo haga: te enseña el cambio antes de guardarlo."]}
CLOSING = {"es": "Estas plantillas fijan lo que un agente puede hacer. Para ver lo que tus agentes alcanzan de verdad en tu ordenador, "
                 "y cómo un agente puede cambiar otro, prueba RosmarOps. Lo comprueba sin que nada salga de tu ordenador."}
GITHUB_LABEL = {"en": "See it on GitHub", "es": "Verlo en GitHub"}
COPY = {"en": ("Copy", "Copied"), "es": ("Copiar", "Copiado")}
GENERATED = re.compile(r"^Generated by RosmarOps (\S+?)\.? Do not edit by hand\.$", re.M)


def esc(s):
    return html.escape(str(s), quote=True)


def repo_readme(path=None):
    """The steps of «How to use them» and the closing paragraph, from the templates repository's README (EN)."""
    text = (path or EXPORT.parent / "README.md").read_text(encoding="utf-8")
    use = re.search(r"## How to use them\n(.*?)\n\n", text, re.S).group(1)
    steps = [re.sub(r"^\d+\.\s*", "", l).strip() for l in use.splitlines() if l.strip()]
    steps = [re.sub(r"`([^`]+)`", r"<code>\1</code>", esc(s).replace("&#x60;", "`")) for s in steps]
    closing = re.search(r"## What can your agents actually do\?\n(.*?)(?:\n\n|$)", text, re.S).group(1).strip()
    closing = re.sub(r":\s*https://rosmarops\.com/?$", ".", closing)  # the page itself is on rosmarops.com
    return steps, closing


def load(export=EXPORT, catalog_es=None):
    """{template: {"file", "name", "en": description, "es": description, "version"}} for the templates whose export is
    here; {} until BV-266's export is copied in. Stops (raises) when a piece the page needs is missing."""
    out = {}
    for tid, folder in FOLDER.items():
        d = export / folder if folder else None
        if d is None or not d.is_dir():
            continue
        readme = (d / "README.md").read_text(encoding="utf-8")
        m = GENERATED.search(readme)
        if not m:
            raise SystemExit(f"GTM-190 PARA: {d}/README.md has no «Generated by RosmarOps <version>.» line")
        files = [f for f in d.iterdir() if f.name != "README.md" and f.is_file()]
        if len(files) != 1:
            raise SystemExit(f"GTM-190 PARA: {d} should hold one settings file, it holds {len(files)}")
        desc_en = readme[:m.start()].strip()
        desc_es = (catalog_es or {}).get(tid)
        if not desc_es:
            raise SystemExit(f"GTM-190 PARA: no ES catalog text for {tid}")
        out[tid] = {"file": files[0].read_text(encoding="utf-8"), "name": files[0].name, "folder": folder,
                    "en": desc_en, "es": desc_es, "version": m.group(1)}
    return out


def paragraphs(text):
    return "".join(f"<p>{esc(p.strip())}</p>" for p in re.split(r"\n\s*\n", text) if p.strip())


def download_row(lang):
    """The homepage's download buttons (Microsoft Store, Mac, Linux), with from=templates."""
    store = {"en": "/assets/store/microsoft-store-en.svg", "es": "/assets/store/microsoft-store-es.svg"}[lang]
    alt = {"en": "Download from the Microsoft Store", "es": "Descargar desde Microsoft Store"}[lang]
    mac, linux = {"en": ("/macos/", "Mac (preview)"), "es": ("/es/macos/", "Mac (vista previa)")}[lang], {"en": "/linux/", "es": "/es/linux/"}[lang]
    return (f'<div class="dlrow"><a class="sbadge" href="/download?from=templates&amp;os=store" target="_blank" rel="nofollow noopener">'
            f'<img src="{store}" width="161" height="44" alt="{esc(alt)}"></a><a class="hbtn sec" href="{mac[0]}">{esc(mac[1])}</a>'
            f'<a class="hbtn sec" href="{linux}">Linux</a></div>')


def template_body(lang, tid, t, steps, closing):
    path, title = PAGES[tid][lang]
    copy, copied = COPY[lang]
    pid = f"tpl-{tid.lower()}"
    step_items = "".join(f"<li>{s}</li>" for s in steps)
    gh = f"{REPO}/blob/main/templates/claude-code/{t['folder']}/{t['name']}"
    return f"""<article class="sg">
<header class="sg-head"><h1>{esc(title)}</h1></header>
<div class="doc">
<section class="doc">{paragraphs(t[lang])}</section>
<div class="sg-box"><h3><code>{esc(DEST)}</code></h3>
<button type="button" class="tb-copy" data-copy="{pid}" data-copied="{esc(copied)}">{esc(copy)}</button>
<pre id="{pid}"><code>{esc(t["file"].rstrip())}</code></pre></div>
<section class="doc"><ol>{step_items}</ol></section>
<p><a href="{gh}">{esc(GITHUB_LABEL[lang])}</a></p>
<section class="doc"><p>{esc(closing)}</p>{download_row(lang)}</section>
<p class="sg-note">Generated by RosmarOps {esc(t["version"])}.</p>
</div>
</article>"""


def index_body(lang, data):
    title = {"en": "Templates", "es": "Plantillas"}[lang]
    items = "".join(f'<li><a href="{PAGES[t][lang][0]}">{esc(PAGES[t][lang][1])}</a></li>' for t in PAGES if t in data)
    return f"""<article class="sg">
<header class="sg-head"><h1>{esc(title)}</h1></header>
<section class="doc"><ul>{items}</ul><p><a href="{REPO}">{REPO.replace("https://", "")}</a></p></section>
</article>"""


def switch_langs(block, lang, alt_paths):
    """The shell's language links point to this page in the other language; no CA link while there is no CA page."""
    block = re.sub(r'<a href="[^"]*" hreflang="ca"[^>]*>CA</a>', "", block)
    for o, p in alt_paths.items():
        if o != lang:
            block = re.sub(r'<a href="[^"]*" hreflang="%s"' % o, f'<a href="{p}" hreflang="{o}"', block)
    return block


def page_html(lang, path, alt_paths, title, desc, body):
    """The sandbox guide's shell (head, header, footer, styles, its copy script), without structured data."""
    style, header, footer, _scripts = sandbox_section.shell_parts(lang)
    url = "https://rosmarops.com" + path
    alts = "".join(f'<link rel="alternate" hreflang="{l}" href="https://rosmarops.com{p}">\n' for l, p in alt_paths.items())
    alts += f'<link rel="alternate" hreflang="x-default" href="https://rosmarops.com{alt_paths["en"]}">\n'
    return f"""<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)} · RosmarOps</title>
<meta name="description" content="{esc(desc)}">
<link rel="canonical" href="{url}">
{alts}{style.strip()}
<style>
{sandbox_section.GUIDE_CSS}
</style>
</head>
<body>
{switch_langs(header, lang, alt_paths)}

<main><div class="wrap">
{body}
</div></main>

{switch_langs(footer, lang, alt_paths)}
{sandbox_section.GUIDE_SCRIPT}
</body>
</html>
"""


def pages(data, readme=None):
    """{site path: html} for the pages to write; empty until the export is here."""
    if not data:
        return {}
    steps_en, closing_en = repo_readme(readme)
    steps, closing = {"en": steps_en, "es": STEPS["es"]}, {"en": closing_en, "es": CLOSING["es"]}
    out = {}
    for lang in LANGS:
        for tid, t in data.items():
            path, title = PAGES[tid][lang]
            desc = re.split(r"(?<=\.)\s", t[lang].strip(), 1)[0]
            out[path] = page_html(lang, path, {l: PAGES[tid][l][0] for l in LANGS}, title, desc,
                                  template_body(lang, tid, t, steps[lang], closing[lang]))
        out[INDEX[lang]] = page_html(lang, INDEX[lang], INDEX, {"en": "Templates", "es": "Plantillas"}[lang],
                                     PAGES["P0"][lang][1], index_body(lang, data))
    return out


def sitemap_urls(data):
    """(path, {lang: path}) for sitemap-pages.xml, with hreflang EN<->ES; empty until the pages exist."""
    if not data:
        return []
    groups = [{l: INDEX[l] for l in LANGS}] + [{l: PAGES[t][l][0] for l in LANGS} for t in PAGES if t in data]
    return [(g[l], g) for g in groups for l in LANGS]


def llms_lines(data):
    """The three questions with their URL, for llms.txt (EN); empty until the pages exist."""
    return [f"- [{PAGES[t]['en'][1]}](https://rosmarops.com{PAGES[t]['en'][0]})" for t in PAGES if t in data]


def footer_link(lang, data):
    """GTM-190: «Templates» in the footer, to the EN page, once the pages exist."""
    return f'<a href="{INDEX["en"]}">{FOOTER_LABEL[lang]}</a>' if data else ""


def build(site=SITE, data=None, readme=None):
    data = load() if data is None else data
    for path, text in pages(data, readme).items():
        f = Path(site) / path.strip("/") / "index.html"
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")
    return data

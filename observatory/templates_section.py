"""The question pages with the Claude Code templates (GTM-190, signed by Albert 20-11 06:46): /templates/ and
/es/plantillas/, an index and one page per template, in English and Spanish (Catalan waits for the program's catalog).

Every visible text is literal: the titles, the three steps and the closing paragraph are in
observatory/i18n/templates.json. The description of each template, its file and the «Generated by RosmarOps
<version>.» line come from the export that BV-266 writes to qtorb/rosmarops-templates, copied unchanged to
observatory/data/templates/. Until that export is here, a page leaves those three parts out, with an HTML comment
in their place. Same shell, styles and copy button as the «Sandbox» section; nothing new.
"""

import json
from pathlib import Path

import sandbox_section as sb

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
TEXTS = ROOT / "observatory" / "i18n" / "templates.json"
EXPORT = ROOT / "observatory" / "data" / "templates"
LANGS = ("en", "es")
REPO = "https://github.com/qtorb/rosmarops-templates"
INDEX_PATH = {"en": "/templates/", "es": "/es/plantillas/"}
# The template of the report each page shows, and its address in each language (GTM-190, literal).
PAGES = {
    "P0": {"en": "/templates/claude-code-read-only/", "es": "/es/plantillas/claude-code-solo-lectura/"},
    "P1": {"en": "/templates/claude-code-no-web/", "es": "/es/plantillas/claude-code-sin-web/"},
    "P2": {"en": "/templates/claude-code-sandbox/", "es": "/es/plantillas/claude-code-sandbox/"},
}
# The export's folder of each template, under templates/claude-code/. BV-266 names them; None until it does.
EXPORT_USE = {"P0": None, "P1": None, "P2": None}
DEST = ".claude/settings.json"
# The download button of the closing paragraph: the home page's, with this section as its source.
FROM = "templates"


def texts():
    return json.loads(TEXTS.read_text(encoding="utf-8"))


def footer_link(lang):
    """The footer link of every page (GTM-190): to the English index, with the label of the page's language."""
    return f'<a href="{INDEX_PATH["en"]}">{sb.esc(texts()["footer"][lang])}</a>'


def exported(pid, export=EXPORT):
    """(description, file text, «Generated by» line) of the template from BV-266's export, or None."""
    use = EXPORT_USE.get(pid)
    if not use:
        return None
    d = Path(export) / "claude-code" / use
    if not (d / "README.md").is_file() or not (d / DEST).is_file():
        return None
    lines = [l for l in (d / "README.md").read_text(encoding="utf-8").splitlines() if l.strip()]
    gen = next((l for l in lines if l.startswith("Generated by RosmarOps")), None)
    desc = [l for l in lines if l is not gen and not l.startswith("#")]
    return " ".join(desc), (d / DEST).read_text(encoding="utf-8"), gen


def download(lang):
    route, l, alt, mac, mac_label, linux = sb.DOWNLOAD[lang]
    return (f'<div class="dlrow"><a class="sbadge" href="{route}?from={FROM}&amp;os=store" target="_blank" rel="nofollow noopener">'
            f'<img src="/assets/store/microsoft-store-{l}.svg" width="161" height="44" alt="{sb.esc(alt)}"></a>'
            f'<a class="hbtn sec" href="{mac}">{sb.esc(mac_label)}</a><a class="hbtn sec" href="{linux}">Linux</a></div>')


def article(lang, pid, export=EXPORT):
    T = texts()[lang]
    parts = [f"<h1>{sb.esc(T[pid])}</h1>"]
    got = exported(pid, export)
    if got:
        desc, text, gen = got
        G = sb.gtexts()[lang]
        tid = f"tpl-{pid.lower()}"
        parts += [f"<p>{sb.esc(desc)}</p>", f"<p><code>{DEST}</code></p>",
                  f'<div class="sg-cmdrow"><pre id="{tid}">{sb.esc(text)}</pre>'
                  f'<button type="button" class="tb-copy" data-copy="{tid}" data-copied="{sb.esc(G["copied"])}">'
                  f'{sb.esc(sb.texts()[lang]["copy"])}</button></div>']
    else:
        gen = None
        parts.append("<!-- GTM-190: the description and the file come from the BV-266 export, not here yet -->")
    parts.append("<ol>" + "".join(f"<li>{sb.code(s)}</li>" for s in T["steps"]) + "</ol>")
    where = f"{REPO}/tree/main/templates/claude-code/{EXPORT_USE[pid]}" if EXPORT_USE.get(pid) else f"{REPO}/tree/main/templates"
    parts.append(f'<p><a href="{where}" target="_blank" rel="noopener">{sb.esc(T["github"])}</a></p>')
    parts.append(f"<p>{sb.esc(T['end'])}</p>{download(lang)}")
    parts.append(f'<p class="meta">{sb.esc(gen)}</p>' if gen else "<!-- GTM-190: the «Generated by» line comes from the export -->")
    return '<article class="doc">' + "".join(parts) + "</article>"


def index_article(lang):
    T = texts()[lang]
    items = "".join(f'<li><a href="{PAGES[p][lang]}">{sb.esc(T[p])}</a></li>' for p in PAGES)
    return (f'<article class="doc"><h1>{sb.esc(T["index_h1"])}</h1><ul>{items}</ul>'
            f'<p><a href="{REPO}" target="_blank" rel="noopener">{sb.esc(T["repo"])}</a></p></article>')


def nav(block, lang, paths):
    """The guide's navigation, with the language links pointing to this page (Catalan to the English one)."""
    import re
    for o in sb.LANGS:
        if o != lang:
            block = re.sub(r'<a href="[^"]*" hreflang="%s"' % o, f'<a href="{paths.get(o, paths["en"])}" hreflang="{o}"', block)
    return block


def page(lang, paths, title, body):
    style, header, footer, scripts = sb.shell_parts(lang)
    url = "https://rosmarops.com" + paths[lang]
    alts = "".join(f'<link rel="alternate" hreflang="{o}" href="https://rosmarops.com{paths[o]}">\n' for o in LANGS)
    alts += f'<link rel="alternate" hreflang="x-default" href="https://rosmarops.com{paths["en"]}">\n'
    copy_js = sb.GUIDE_SCRIPT[sb.GUIDE_SCRIPT.index("document.querySelectorAll('.tb-copy"):]
    return f"""<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{sb.esc(title)} · RosmarOps</title>
<link rel="canonical" href="{url}">
{alts}{style.strip()}
<style>
{sb.GUIDE_CSS}
</style>
</head>
<body>
{nav(header, lang, paths)}

<main><div class="wrap">
{body}
</div></main>

{nav(footer, lang, paths)}
{scripts}
<script>
{copy_js}
</body>
</html>
"""


def all_paths():
    """Every page of the section as (paths by language, template id or None for the index)."""
    return [(INDEX_PATH, None)] + [(PAGES[p], p) for p in PAGES]


def build(site=SITE, export=EXPORT):
    for paths, pid in all_paths():
        for lang in LANGS:
            T = texts()[lang]
            title, body = (T["index_h1"], index_article(lang)) if pid is None else (T[pid], article(lang, pid, export))
            out = Path(site) / paths[lang].strip("/") / "index.html"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(page(lang, paths, title, body), encoding="utf-8")

"""GTM-190: the Claude Code template pages, against a synthetic export (BV-266's is not in the repository yet)."""

import re
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "observatory"))
import templates_pages as tp  # noqa: E402

FORBIDDEN = re.compile(r"\b(secure|safe|protects?|segur[oa]s?|protege)\b", re.I)


# The templates repository's README (qtorb/rosmarops-templates main, GTM-188 §3), as the export copies it.
REPO_README = """# RosmarOps templates

Settings that make your AI coding agent ask before it acts.

## How to use them
1. Open the folder of your agent in `templates/`.
2. Pick the use that fits how you work. Each one says what the agent can do without asking and what it asks first.
3. Copy the file into your project, or ask the RosmarOps skill to do it: it shows you the change before saving it.

## What can your agents actually do?
These templates set what an agent may do. To see what your agents can really reach on your computer, and how one agent can change another, try RosmarOps. It checks without anything leaving your computer: https://rosmarops.com

## Licence
The templates in this repository are MIT-licensed.
"""


def fake_export(d):
    """A synthetic export: one folder per use, README with a description and the generated line, one settings file."""
    folders = {"P0": "read-only", "P1": "no-web", "P2": "sandbox"}
    (Path(d) / "README.md").write_text(REPO_README, encoding="utf-8")
    for tid, f in folders.items():
        p = Path(d) / f
        p.mkdir(parents=True)
        (p / "README.md").write_text(f"Synthetic description of {tid}.\n\nGenerated by RosmarOps 9.9.9. Do not edit by hand.\n")
        (p / "settings.json").write_text('{\n  "permissions": {"deny": ["WebFetch"]}\n}\n')
    return folders


class Empty(unittest.TestCase):
    def test_nothing_until_the_export_is_here(self):
        with tempfile.TemporaryDirectory() as d:
            data = tp.load(export=Path(d) / "none")
            self.assertEqual(data, {})
            self.assertEqual(tp.pages(data), {})
            self.assertEqual(tp.sitemap_urls(data), [])
            self.assertEqual(tp.llms_lines(data), [])
            self.assertEqual(tp.footer_link("en", data), "")
        self.assertFalse((ROOT / "site/templates").exists())
        self.assertFalse((ROOT / "site/es/plantillas").exists())


class WithExport(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.folders = fake_export(self.tmp.name)
        self.saved = dict(tp.FOLDER)
        tp.FOLDER.update(self.folders)
        self.data = tp.load(export=Path(self.tmp.name), catalog_es={t: f"Descripción sintética de {t}." for t in tp.PAGES})
        self.out = tp.pages(self.data, readme=Path(self.tmp.name) / "README.md")

    def tearDown(self):
        tp.FOLDER.clear()
        tp.FOLDER.update(self.saved)
        self.tmp.cleanup()

    def test_paths_and_titles(self):
        self.assertEqual(set(self.out), {tp.PAGES[t][l][0] for t in tp.PAGES for l in tp.LANGS} | set(tp.INDEX.values()))
        for t in tp.PAGES:
            for l in tp.LANGS:
                path, title = tp.PAGES[t][l]
                self.assertIn(f"<h1>{tp.esc(title)}</h1>", self.out[path])

    def test_order_of_a_page(self):
        for l in tp.LANGS:
            p = self.out[tp.PAGES["P1"][l][0]]
            p = p[p.index("<main>"):p.index("</main>")]
            marks = ["<h1>", tp.esc(self.data["P1"][l]), tp.esc(tp.DEST), 'class="tb-copy"', "<ol>",
                     tp.GITHUB_LABEL[l], 'class="dlrow"', "Generated by RosmarOps 9.9.9."]
            pos = [p.index(m) for m in marks]
            self.assertEqual(pos, sorted(pos), l)
            self.assertIn('{\n  &quot;permissions&quot;', p)
            self.assertIn(f"{tp.REPO}/blob/main/templates/claude-code/no-web/settings.json", p)

    def test_hreflang_and_no_structured_data(self):
        for path, p in self.out.items():
            self.assertNotIn("application/ld+json", p)
            self.assertIn('hreflang="en"', p)
            self.assertIn('hreflang="es"', p)
            self.assertNotIn('hreflang="ca"', p)
            self.assertNotIn('href="/sandbox/" hreflang', p)

    def test_texts(self):
        en = self.out[tp.PAGES["P0"]["en"][0]]
        self.assertIn("<li>Open the folder of your agent in <code>templates/</code>.</li>", en)
        self.assertIn("It checks without anything leaving your computer.</p>", en)
        es = self.out[tp.PAGES["P0"]["es"][0]]
        for s in tp.STEPS["es"]:
            self.assertIn(s, es)
        self.assertIn(tp.CLOSING["es"], es)
        for p in self.out.values():
            body = re.sub(r"<[^>]+>", " ", p[p.index("<main>"):p.index("</main>")])
            self.assertFalse(FORBIDDEN.search(body))

    def test_sitemap_llms_footer(self):
        urls = tp.sitemap_urls(self.data)
        self.assertEqual(len(urls), 8)
        self.assertEqual(len(tp.llms_lines(self.data)), 3)
        self.assertEqual(tp.footer_link("ca", self.data), '<a href="/templates/">Plantilles</a>')

    def test_missing_es_text_stops(self):
        with self.assertRaises(SystemExit):
            tp.load(export=Path(self.tmp.name), catalog_es={})


if __name__ == "__main__":
    unittest.main()

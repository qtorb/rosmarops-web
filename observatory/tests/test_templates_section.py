"""GTM-190: the template question pages (/templates/, /es/plantillas/), their links and the footer link."""

import re
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "observatory"))
import templates_section as ts  # noqa: E402

SITE = ROOT / "site"


class Pages(unittest.TestCase):
    def test_every_page_is_built_with_its_literal_title_and_hreflang(self):
        for paths, pid in ts.all_paths():
            for lang in ts.LANGS:
                html = (SITE / paths[lang].strip("/") / "index.html").read_text(encoding="utf-8")
                title = ts.texts()[lang]["index_h1" if pid is None else pid]
                self.assertIn(f"<h1>{ts.sb.esc(title)}</h1>", html)
                for o in ts.LANGS:
                    self.assertIn(f'hreflang="{o}" href="https://rosmarops.com{paths[o]}"', html)
                self.assertNotIn('hreflang="ca" href="https://rosmarops.com', html.split("<body>")[0])

    def test_no_forbidden_words(self):
        for f in list((SITE / "templates").rglob("*.html")) + list((SITE / "es" / "plantillas").rglob("*.html")):
            text = re.sub(r"<[^>]+>", " ", f.read_text(encoding="utf-8")).lower()
            for w in ("secure", "safe", "protects", "seguro", "segura", "protege"):
                self.assertNotRegex(text, r"\b%s\b" % w, f)

    def test_index_links_the_three_questions_and_the_repository(self):
        html = (SITE / "templates" / "index.html").read_text(encoding="utf-8")
        for p in ts.PAGES:
            self.assertIn(f'href="{ts.PAGES[p]["en"]}"', html)
        self.assertIn(f'href="{ts.REPO}"', html)

    def test_sitemap_and_llms(self):
        sm = (SITE / "sitemap-pages.xml").read_text(encoding="utf-8")
        llms = (SITE / "llms.txt").read_text(encoding="utf-8")
        for paths, pid in ts.all_paths():
            for lang in ts.LANGS:
                self.assertIn(f"<loc>https://rosmarops.com{paths[lang]}</loc>", sm)
            if pid:
                self.assertIn(f"https://rosmarops.com{paths['en']})", llms)

    def test_every_footer_links_the_templates(self):
        for f in SITE.rglob("*.html"):
            s = f.read_text(encoding="utf-8")
            if "<footer>" in s:
                foot = s[s.index("<footer>"):s.index("</footer>")]
                self.assertIn('<a href="/templates/">', foot, f)


class Export(unittest.TestCase):
    def test_without_export_the_three_parts_are_left_out(self):
        html = ts.article("en", "P0", export=Path("/nonexistent"))
        self.assertNotIn("<pre", html)
        self.assertNotIn("Generated by RosmarOps", html)

    def test_with_export_the_description_file_and_line_are_shown_unchanged(self):
        with tempfile.TemporaryDirectory() as d:
            use = Path(d) / "claude-code" / "read-only"
            (use / ".claude").mkdir(parents=True)
            (use / ".claude" / "settings.json").write_text('{"permissions": {}}\n', encoding="utf-8")
            (use / "README.md").write_text("The description.\n\nGenerated by RosmarOps 0.16.0. Do not edit by hand.\n", encoding="utf-8")
            old = dict(ts.EXPORT_USE)
            ts.EXPORT_USE["P0"] = "read-only"
            try:
                html = ts.article("en", "P0", export=Path(d))
            finally:
                ts.EXPORT_USE.clear()
                ts.EXPORT_USE.update(old)
        self.assertIn("<p>The description.</p>", html)
        self.assertIn("{&quot;permissions&quot;: {}}", html)
        self.assertIn("Generated by RosmarOps 0.16.0", html)
        self.assertIn('class="tb-copy"', html)
        self.assertIn("/tree/main/templates/claude-code/read-only", html)


if __name__ == "__main__":
    unittest.main()

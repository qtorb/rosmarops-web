<?php
/**
 * Plugin Name: RosmarOps downloads and visits
 * Description: Download counter (GTM-18; os added by the 2026-10-29 direct-download decision). /download, /es/descargar and /ca/descarregar add one to an aggregate count (UTC day, source page, language, os) and redirect to GitHub: to the file for ?os=windows|mac-arm|mac-intel|linux-amd64|linux-arm64 (Linux added by GTM-83), otherwise to the latest release. Stores no IP address, cookie, user agent or referrer; requests with the WordPress session cookie (the team, signed in) are not counted (GTM-111). Public read-only totals at /wp-json/rosmarops/v1/downloads. Versioned in qtorb/rosmarops-web; do not edit on the server.
 *
 * GTM-111: visit counter, behind ROSMAROPS_VISITS_ON (off). Pages send their path and the referrer's domain with JavaScript (/assets/visits/visits.js); the server adds one to (UTC day, page, language, referrer kind), with closed lists. It stores no IP address, cookie, user agent, exact time or identifier. Public read-only totals at /wp-json/rosmarops/v1/visits.
 */

if (!defined('ABSPATH')) {
	exit;
}

const ROSMAROPS_DL_TARGET = 'https://github.com/qtorb/rosmarops/releases/latest';
const ROSMAROPS_DL_ROUTES = ['/download' => 'en', '/es/descargar' => 'es', '/ca/descarregar' => 'ca'];
// Closed list of ?os= values and their direct targets. Absent or unknown: ROSMAROPS_DL_TARGET, stored as ''.
const ROSMAROPS_DL_OS     = [
	'windows'   => 'https://github.com/qtorb/rosmarops/releases/latest/download/rosmarops.exe',
	'mac-arm'   => 'https://github.com/qtorb/rosmarops/releases/latest/download/rosmarops-macos-apple-silicon',
	'mac-intel' => 'https://github.com/qtorb/rosmarops/releases/latest/download/rosmarops-macos-intel',
	'linux-amd64' => 'https://github.com/qtorb/rosmarops/releases/latest/download/rosmarops-linux-amd64',
	'linux-arm64' => 'https://github.com/qtorb/rosmarops/releases/latest/download/rosmarops-linux-arm64',
];
const ROSMAROPS_DL_FROM   = [
	'home', 'home-band', 'faq', 'about', 'macos-page', 'linux-page',
	'blog-v040', 'blog-v030', 'blog-launch', 'blog-18of100',
	// observatory:published-start (generated by observatory/build.py from PUBLISHED_AGENT_PAGES; do not edit by hand)
	'observatory-antigravity',
	'observatory-claude-code',
	'observatory-cursor',
	'observatory-github-copilot',
	'observatory-hermes-agent',
	'observatory-kanvas',
	// observatory:published-end
];
const ROSMAROPS_DL_DAYS   = 400;

function rosmarops_dl_table() {
	global $wpdb;
	return $wpdb->base_prefix . 'rosmarops_downloads';
}

/** Language of a download route for a request URI, or null if it is not one. */
function rosmarops_dl_route_lang($request_uri) {
	$path = parse_url((string) $request_uri, PHP_URL_PATH);
	if (!is_string($path)) {
		return null;
	}
	$path = rtrim($path, '/');
	return ROSMAROPS_DL_ROUTES[$path] ?? null;
}

/** Source page from ?from=, limited to the closed list; anything else is "other". */
function rosmarops_dl_source($raw) {
	return (is_string($raw) && in_array($raw, ROSMAROPS_DL_FROM, true)) ? $raw : 'other';
}

/** The ?os= key if it is on the closed list, otherwise '' (latest release). */
function rosmarops_dl_os($raw) {
	return (is_string($raw) && isset(ROSMAROPS_DL_OS[$raw])) ? $raw : '';
}

/**
 * GTM-111: a request from someone on the team, signed in to this WordPress: it carries the session cookie WordPress
 * already sets (wordpress_logged_in_<hash>). Only its presence is checked; nothing is read from it, stored or set.
 */
function rosmarops_is_team($cookies) {
	foreach (array_keys((array) $cookies) as $name) {
		if (strpos((string) $name, 'wordpress_logged_in_') === 0) {
			return true;
		}
	}
	return false;
}

/** Redirect target for an os key. */
function rosmarops_dl_target($os) {
	return ROSMAROPS_DL_OS[$os] ?? ROSMAROPS_DL_TARGET;
}

/**
 * Creates the table, or brings a table from before the os column up to date.
 * The migration is one ALTER: existing rows keep their counts with os = '', and stay unique
 * because the old key (day, src, lang) is a prefix of the new one.
 */
function rosmarops_dl_create_table() {
	global $wpdb;
	$t = rosmarops_dl_table();
	$wpdb->query(
		"CREATE TABLE IF NOT EXISTS `$t` (
			day DATE NOT NULL,
			src VARCHAR(40) NOT NULL,
			lang CHAR(2) NOT NULL,
			os VARCHAR(16) NOT NULL DEFAULT '',
			count INT UNSIGNED NOT NULL DEFAULT 0,
			PRIMARY KEY (day, src, lang, os)
		) " . $wpdb->get_charset_collate()
	);
	$cols = $wpdb->get_results("SHOW COLUMNS FROM `$t` LIKE 'os'", ARRAY_A);
	if (is_array($cols) && count($cols) === 0) {
		$wpdb->query("ALTER TABLE `$t` ADD COLUMN os VARCHAR(16) NOT NULL DEFAULT '' AFTER lang, DROP PRIMARY KEY, ADD PRIMARY KEY (day, src, lang, os)");
	}
}

/** Adds one to (UTC day, source, language, os). Only this table is written. */
function rosmarops_dl_count($src, $lang, $os = '', $day = null) {
	global $wpdb;
	$t   = rosmarops_dl_table();
	$day = $day ?? gmdate('Y-m-d');
	$sql = $wpdb->prepare(
		"INSERT INTO `$t` (day, src, lang, os, count) VALUES (%s, %s, %s, %s, 1) ON DUPLICATE KEY UPDATE count = count + 1",
		$day,
		$src,
		$lang,
		$os
	);
	$suppress = $wpdb->suppress_errors(true);
	$ok       = $wpdb->query($sql);
	if ($ok === false) {
		rosmarops_dl_create_table();
		$ok = $wpdb->query($sql);
	}
	$wpdb->suppress_errors($suppress);
	return $ok !== false;
}

/** Aggregate rows of the last ROSMAROPS_DL_DAYS days (UTC), oldest first. */
function rosmarops_dl_rows($today = null) {
	global $wpdb;
	$t     = rosmarops_dl_table();
	$today = $today ?? gmdate('Y-m-d');
	$since = gmdate('Y-m-d', strtotime($today . ' UTC') - (ROSMAROPS_DL_DAYS - 1) * 86400);
	$sql      = $wpdb->prepare("SELECT day, src, lang, os, count FROM `$t` WHERE day >= %s ORDER BY day, src, lang, os", $since);
	$suppress = $wpdb->suppress_errors(true);
	$res      = $wpdb->get_results($sql, ARRAY_A);
	if ($res === null || $wpdb->last_error !== '') { // WordPress returns [] on a failed ARRAY_A query
		rosmarops_dl_create_table(); // a table from before the os column
		$res = $wpdb->get_results($sql, ARRAY_A);
	}
	$wpdb->suppress_errors($suppress);
	$rows = [];
	foreach ((array) $res as $r) {
		$rows[] = ['day' => $r['day'], 'from' => $r['src'], 'lang' => $r['lang'], 'os' => $r['os'], 'count' => (int) $r['count']];
	}
	return $rows;
}

// Redirect + count, before WordPress resolves the request (no page, no 404).
add_action('muplugins_loaded', function () {
	$method = $_SERVER['REQUEST_METHOD'] ?? 'GET';
	$lang   = rosmarops_dl_route_lang($_SERVER['REQUEST_URI'] ?? '');
	if ($lang === null || ($method !== 'GET' && $method !== 'HEAD')) {
		return;
	}
	$os = rosmarops_dl_os($_GET['os'] ?? null);
	if ($method === 'GET' && !rosmarops_is_team($_COOKIE)) {
		rosmarops_dl_count(rosmarops_dl_source($_GET['from'] ?? null), $lang, $os);
	}
	header('Cache-Control: no-store');
	header('Location: ' . rosmarops_dl_target($os), true, 302);
	exit;
});

// Public, read-only totals. Only GET is registered, so any other method gets no route.
add_action('rest_api_init', function () {
	register_rest_route('rosmarops/v1', '/downloads', [
		'methods'             => 'GET',
		'permission_callback' => '__return_true',
		'callback'            => function () {
			$res = new WP_REST_Response([
				'generated_at' => gmdate('Y-m-d\TH:i:s\Z'),
				'rows'         => rosmarops_dl_rows(),
			]);
			$res->header('Cache-Control', 'public, max-age=3600');
			return $res;
		},
	]);
});


// ------------------------------------------------------------------------------------------------- visits (GTM-111)

// On since the privacy policy texts for it were signed (Albert, 07-11, GTM-111 C). Must match ON in site/assets/visits/visits.js.
if (!defined('ROSMAROPS_VISITS_ON')) {
	define('ROSMAROPS_VISITS_ON', true);
}
const ROSMAROPS_VISITS_ORIGIN    = 'https://rosmarops.com';
const ROSMAROPS_VISITS_MAX_BODY  = 512;
const ROSMAROPS_VISITS_BLOGS     = ['/blog/', '/es/blog/', '/ca/blog/'];
// Referrer domains, closed list: the first matching rule wins (gemini before google). Anything else is "other";
// none is "direct"; rosmarops.com itself is "internal".
const ROSMAROPS_VISITS_REFS      = [
	['gemini', '/^gemini\.google\.com$/'],
	['google', '/(^|\.)google\.[a-z]{2,3}(\.[a-z]{2})?$/'],
	['bing', '/(^|\.)bing\.com$/'],
	['duckduckgo', '/(^|\.)duckduckgo\.com$/'],
	['github', '/(^|\.)github\.com$/'],
	['linkedin', '/(^|\.)(linkedin\.com|lnkd\.in)$/'],
	['x', '/^(x\.com|t\.co|twitter\.com|mobile\.twitter\.com)$/'],
	['hn', '/^news\.ycombinator\.com$/'],
	['reddit', '/(^|\.)reddit\.com$/'],
	['chatgpt', '/^(chatgpt\.com|chat\.openai\.com)$/'],
	['perplexity', '/(^|\.)perplexity\.ai$/'],
	['claude', '/^claude\.ai$/'],
];
// User agents that are not a person reading: looked at, never stored.
const ROSMAROPS_VISITS_BOTS      = '/bot|crawl|spider|slurp|headless|lighthouse|preview|python|curl|wget|go-http|java\/|httpclient|okhttp|axios|node-fetch|scrapy|facebookexternalhit|embedly|monitor|uptime|phantom|selenium|playwright|puppeteer/i';

function rosmarops_visits_table() {
	global $wpdb;
	return $wpdb->base_prefix . 'rosmarops_visits';
}

function rosmarops_visits_create_table() {
	global $wpdb;
	$t = rosmarops_visits_table();
	$wpdb->query(
		"CREATE TABLE IF NOT EXISTS `$t` (
			day DATE NOT NULL,
			page VARCHAR(160) NOT NULL,
			lang CHAR(2) NOT NULL,
			ref VARCHAR(16) NOT NULL,
			count INT UNSIGNED NOT NULL DEFAULT 0,
			PRIMARY KEY (day, page, lang, ref)
		) " . $wpdb->get_charset_collate()
	);
}

/** Folder that holds the static pages (site/ is deployed next to WordPress). */
function rosmarops_visits_docroot() {
	return defined('ROSMAROPS_VISITS_DOCROOT') ? ROSMAROPS_VISITS_DOCROOT : ABSPATH;
}

/** True if the path is a page of this site: a static page, a blog home, or a published post or page. */
function rosmarops_visits_page_exists($path) {
	$file = rtrim(rosmarops_visits_docroot(), '/') . $path . 'index.html';
	if (is_file($file) || in_array($path, ROSMAROPS_VISITS_BLOGS, true)) {
		return true;
	}
	// The daily synopsis pages (rosmarops-daily.php): its index and one page per date. Only the shape is checked.
	foreach (['/observatory/daily/', '/es/observatorio/diario/', '/ca/observatori/diari/'] as $prefix) {
		if ($path === $prefix || preg_match('#^' . preg_quote($prefix, '#') . '\d{4}-\d{2}-\d{2}/$#', $path)) {
			return true;
		}
	}
	return function_exists('url_to_postid') && url_to_postid(ROSMAROPS_VISITS_ORIGIN . $path) > 0;
}

/** The page from the path the browser sent: lowercase letters, digits, hyphens and slashes, an existing page; else "other". */
function rosmarops_visits_page($raw) {
	if (!is_string($raw) || strlen($raw) > 150 || !preg_match('#^/[a-z0-9/-]*$#', $raw) || strpos($raw, '//') !== false) {
		return 'other';
	}
	$path = rtrim($raw, '/') . '/';
	return rosmarops_visits_page_exists($path) ? $path : 'other';
}

/** Language from the page path, never from the browser. */
function rosmarops_visits_lang($page) {
	if (strpos($page, '/es/') === 0) {
		return 'es';
	}
	if (strpos($page, '/ca/') === 0) {
		return 'ca';
	}
	return 'en';
}

/** Kind of referrer from the domain the page sent (only the domain is sent). */
function rosmarops_visits_ref($raw) {
	if (!is_string($raw) || $raw === '') {
		return 'direct';
	}
	$host = strtolower($raw);
	if (strlen($host) > 253 || !preg_match('/^[a-z0-9.-]+$/', $host)) {
		return 'other';
	}
	$host = preg_replace('/^www\./', '', $host);
	if ($host === 'rosmarops.com') {
		return 'internal';
	}
	foreach (ROSMAROPS_VISITS_REFS as [$key, $rx]) {
		if (preg_match($rx, $host)) {
			return $key;
		}
	}
	return 'other';
}

/** Whether a POST counts: from our own pages, not a prefetch, not a bot, not the team. Headers are looked at, never kept. */
function rosmarops_visits_accept($server, $cookies) {
	if (($server['HTTP_ORIGIN'] ?? '') !== ROSMAROPS_VISITS_ORIGIN) {
		return false;
	}
	$purpose = strtolower(($server['HTTP_SEC_PURPOSE'] ?? '') . ' ' . ($server['HTTP_PURPOSE'] ?? '') . ' ' . ($server['HTTP_X_MOZ'] ?? ''));
	if (strpos($purpose, 'prefetch') !== false || strpos($purpose, 'prerender') !== false) {
		return false;
	}
	$ua = (string) ($server['HTTP_USER_AGENT'] ?? '');
	if ($ua === '' || preg_match(ROSMAROPS_VISITS_BOTS, $ua)) {
		return false;
	}
	return !rosmarops_is_team($cookies);
}

/** Adds one to (UTC day, page, language, referrer kind). Only this table is written. */
function rosmarops_visits_count($page, $lang, $ref, $day = null) {
	global $wpdb;
	$t   = rosmarops_visits_table();
	$day = $day ?? gmdate('Y-m-d');
	$sql = $wpdb->prepare(
		"INSERT INTO `$t` (day, page, lang, ref, count) VALUES (%s, %s, %s, %s, 1) ON DUPLICATE KEY UPDATE count = count + 1",
		$day,
		$page,
		$lang,
		$ref
	);
	$suppress = $wpdb->suppress_errors(true);
	$ok       = $wpdb->query($sql);
	if ($ok === false) {
		rosmarops_visits_create_table();
		$ok = $wpdb->query($sql);
	}
	$wpdb->suppress_errors($suppress);
	return $ok !== false;
}

/** Counts a POST body {"p": path, "r": referrer domain}, if the request is accepted. */
function rosmarops_visits_handle($body, $server, $cookies) {
	if (!rosmarops_visits_accept($server, $cookies) || !is_string($body) || strlen($body) > ROSMAROPS_VISITS_MAX_BODY) {
		return false;
	}
	$in = json_decode($body, true);
	if (!is_array($in) || !array_key_exists('p', $in)) {
		return false;
	}
	$page = rosmarops_visits_page($in['p'] ?? null);
	return rosmarops_visits_count($page, rosmarops_visits_lang($page), rosmarops_visits_ref($in['r'] ?? null));
}

/** Aggregate rows of the last ROSMAROPS_DL_DAYS days (UTC), oldest first. */
function rosmarops_visits_rows($today = null) {
	global $wpdb;
	$t     = rosmarops_visits_table();
	$today = $today ?? gmdate('Y-m-d');
	$since = gmdate('Y-m-d', strtotime($today . ' UTC') - (ROSMAROPS_DL_DAYS - 1) * 86400);
	$sql      = $wpdb->prepare("SELECT day, page, lang, ref, count FROM `$t` WHERE day >= %s ORDER BY day, page, lang, ref", $since);
	$suppress = $wpdb->suppress_errors(true);
	$res      = $wpdb->get_results($sql, ARRAY_A);
	$wpdb->suppress_errors($suppress);
	$rows = [];
	foreach ((array) $res as $r) {
		$rows[] = ['day' => $r['day'], 'page' => $r['page'], 'lang' => $r['lang'], 'ref' => $r['ref'], 'count' => (int) $r['count']];
	}
	return $rows;
}

